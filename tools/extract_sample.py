# Usage: python -I -X utf8 tools/extract_sample.py <xlsx> > sample.js
# Pulls the yellow input cells from the Excel model into the app's state shape.
import sys, json, openpyxl
wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
def sheet(prefix): return next(ws for ws in wb.worksheets if ws.title.replace(' ', '').startswith(prefix))
b, s, f = sheet('1.기초입력'), sheet('2.농장'), sheet('1-2.')
ROWS = dict(sows=6, gilts=7, grow=8, feedMain=10, feedOther=11, sold=15, cullSold=16, weight=17, price=19,
            cullRev=24, feedCost=27, labor=28, breeding=29, semen=30, meds=31, manure=32, util=33, repair=34,
            vehicle=35, other=36, depr=37, ownerLabor=39, insurance=40, interest=45)
num = lambda v: v if isinstance(v, (int, float)) else None
months = {k: [num(b.cell(r, c).value) for c in range(5, 17)] for k, r in ROWS.items()}
stages = []
for r in range(6, 15):
    stages.append(dict(group=f.cell(r, 1).value or '', name=f.cell(r, 2).value, days=(f.cell(r, 3).value or '').strip(),
                       ton=num(f.cell(r, 4).value) or 0, price=num(f.cell(r, 5).value) or 0,
                       std=num(f.cell(r, 9).value) or 0, product=f.cell(r, 10).value or ''))
state = dict(farm='예시농장',  # 공개 저장소용 익명화 (원본 농장명 미포함)
             year=2025, yieldRate=b['C18'].value, months=months,
             sim=dict(msy=s['C9'].value, price=s['C11'].value, msyMin=s['C18'].value, msyStep=s['C19'].value,
                      priceMin=s['C20'].value, priceStep=s['C21'].value),
             feedStages=stages)
print('// generated by tools/extract_sample.py from the Excel model — sample farm data')
print('window.SAMPLE = ' + json.dumps(state, ensure_ascii=False) + ';')
